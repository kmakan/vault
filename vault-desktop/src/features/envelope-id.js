// Идентификатор сообщения: из конверта и заглушка для оптимистичной записи
// (ADR-003 Этап 3, партия 17).
//
// ЗДЕСЬ БЫЛО ТРИ ФОРМУЛЫ ЗАГЛУШКИ И НИ ОДНОГО ЕЁ РАСПОЗНАВАНИЯ.
//
// Заглушка ставится, когда id не удалось вытащить из конверта. Формул было три:
//   'local-' + Date.now()                              (send.js ×2, forward.js)
//   'local-' + Date.now().toString(36) + random(5)      (attachments.js)
// и в шести местах по-разному. Хуже: префикс 'local-' НЕ РАЗЛИЧАЛСЯ НИГДЕ.
//
// К ЧЕМУ ЭТО ПРИВОДИТ. history.js::mergePending сопоставляет оптимистичное
// сообщение с настоящим по ТОЧНОМУ равенству id. При заглушке совпадения не
// будет никогда, и оптимистичная запись останется в списке до страховки в
// 10 минут: человек видит своё же сообщение ДВАЖДЫ — как заглушку и как
// настоящее.
//
// И это не экзотика. В attachments.js заглушка ставится на ветке, где конверт
// НЕ построен вовсе (нет ключа группы и нет ключа пира) — то есть обычный
// случай «отправил вложение до готовности криптографии».
//
// ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ.
// 1. Одна формула заглушки на весь проект. Префикс 'pending-' — он читается как
//    «ещё не подтверждено» и не похож на настоящий идентификатор, а это важно:
//    пока заглушка выглядит как настоящая, слияние её не узнаёт по виду.
// 2. Две разные вещи разведены: получение настоящего id (envelopeIdOf) и
//    признак «это заглушка» (isPendingId). Раньше обе задачи решались одной
//    строкой, и вторая не решалась вовсе.
// 3. Счётчик вместо случайности там, где это возможно. Две отправки в одну
//    миллисекунду при чистом Date.now() дали бы ОДИН id, и записи слились бы
//    друг с другом — то же самое, но наоборот: пропало бы сообщение.

// Префикс заглушки. СИМВОЛИЧЕСКИ ВЫБРАН: настоящие идентификаторы такого вида
// не порождают, поэтому любая проверка по префиксу однозначна.
export const PENDING_PREFIX = 'pending-';

// Сколько ждать настоящее письмо, прежде чем считать заглушку неотправленной.
export const PENDING_MATCH_WINDOW_MS = 3 * 60 * 1000;

// Идентификатор из готового конверта. Пустая строка — конверта нет или он не
// разобран; это НЕ ошибка, а штатный случай, и вызывающий обязан решать сам.
// Раньше здесь стояло try { JSON.parse(envelope).id } catch { return '' } —
// в шести местах, с разными отступами и комментариями.
export function envelopeIdOf(envelope) {
  try {
    const obj = JSON.parse(envelope);
    if (!obj || obj.id === undefined || obj.id === null) return '';
    // НЕ `|| ''`: нулевой идентификатор — валидный, а `0 || ''` дал бы пустую
    // строку и подставил заглушку вместо настоящего id. Первая версия модуля
    // проверяла это не сразу и проглотила нулевой id молча.
    return obj.id;
  } catch (e) {
    return '';
  }
}

// Счётчик НЕ насыщается. Первая версия брала seq % 0xffff, и на 65537-й
// заглушке счётчик снова давал то же значение, что и на первой: при подставленной
// (одинаковой) случайности идентификаторы совпадали. Случайность в реальности
// различает их и без счётчика, но полагаться на это — значит оставлять дефект,
// который виден только в тесте с заглушкой случайности. Счётчик без модуля
// растёт, а base36 даёт ему всё меньше символов.
let seq = 0;

// Заглушка для оптимистичной записи.
//
// Счётчик + время + случайность. Счётчик гарантирует уникальность В ПРЕДЕЛАХ
// ПРОЦЕССА даже при совпадении времени до миллисекунды, время и случайность
// дают различимость между перезапусками приложения.
export function pendingIdOf(now = Date.now(), rnd = Math.random()) {
  seq += 1;
  return PENDING_PREFIX
    + now.toString(36)
    + '-' + seq.toString(36)
    + Math.floor(rnd * 0xffffff).toString(36);
}

export function isPendingId(id) {
  return typeof id === 'string' && id.startsWith(PENDING_PREFIX);
}

// Заглушка, соответствующая настоящему сообщению.
//
// Сопоставлять заглушку с настоящим ТОЛЬКО по id бессмысленно — по построению
// они различны. Остаётся содержание и близость по времени: у отправленного
// сейчас письма текст совпадает и оно приходит в течение минут. Именно поэтому
// сравнивается нормализованный текст, а не сырой: время в сообщении
// форматируется локально и может отличаться на секунду.
export function matchesPending(pendingMsg, realMsg, now = Date.now()) {
  if (!pendingMsg || !realMsg || !isPendingId(pendingMsg.id)) return false;
  const norm = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
  if (norm(pendingMsg.content) !== norm(realMsg.content)) return false;
  const ts = now - (pendingMsg._pendingAt || 0);
  return ts >= 0 && ts <= PENDING_MATCH_WINDOW_MS;
}
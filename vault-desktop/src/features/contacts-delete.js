// Удаление контакта (ADR-003 Этап 3, партия 14).
//
// УДАЛЕНИЕ ЛОКАЛЬНОЕ. Ничего не отправляется второй стороне: Contact::delete в
// почтовом мессенджере тоже локальный. Это осознанно — «удалить контакта» у нас
// значит «перестать шифровать ему и забыть его переписку у себя», а не «сообщить
// ему».
//
// ЧЕТЫРЕ ШАГА, И ПОРЯДОК ЗНАЧИТ.
//
// 1. removePeerKey — снести ключ шифрования. Пока ключ есть, переписка остаётся
//    читаемой, то есть удаление не состоялось.
// 2. markContactHandshakeDone — ПОМЕТИТЬ СТАРЫЕ handshake-письма обработанными по
//    uid. Это самое тонкое место, и логика обратна ожидаемой: старые письма
//    должны перестать воскрешать контакта, а НОВЫЕ приглашения после удаления
//    обязаны доходить (их uid не помечен), чтобы повторное добавление было
//    тривиальным — как Contact::create в DC. Если бы шаг пропускали, удалённый
//    контакт вернулся бы сам при следующей обработке папки; если бы помечали по
//    адресу, а не по uid, новые приглашения перестали бы доходить навсегда.
// 3. removeInvitedSender — снять приглашение, которое отправили МЫ. Иначе его
//    старое accept-письмо авто-добавило бы контакта заново.
// 4. removeContact — убрать из in-memory stubs api.js. Без этого контакт
//    «не удаляется» до перезапуска, потому что getContacts() мержит stubs с
//    диском.
//
// ОТКАЗ ЛЮБОГО ШАГА ОСТАНАВЛИВАЕТ ВСЕ ОСТАЛЬНЫЕ. Полуудалённый контакт хуже
// неудалённого: ключ снесён, а запись оставлена — и следующая попытка удаления
// уже ничего не снесёт. Поэтому ошибка пробрасывается, а вызывающий сообщает
// о ней и НЕ применяет состояние.

import api from '../api.js';
import crypto from '../crypto.js';

export async function deleteContactLocally(email) {
  await crypto.removePeerKey(email);
  await api.markContactHandshakeDone(email);
  await api.removeInvitedSender(email);
  await api.removeContact(email);
}

// Что нужно сделать с состоянием компонента после успешного удаления.
//
// Закрытый чат удаляемого контакта сбрасывается: оставить его значит показать
// пустой экран переписки с человеком, которого больше нет. activeChatType
// возвращается в 'chat' — иначе после сброса активным окажется чат (например
// канал) по несуществующему адресу.
//
// reload: контакты надо перечитать, иначе удалённый останется в списке до
// следующего события. Словари peerKeys и peerKeysLoaded вызывающий чистит сам —
// пересоздавать их нельзя, на них завязана реактивность и ссылки в других
// местах, поэтому delete на месте, а не подмена объекта.
export function contactRemovalState(email, state = {}) {
  const closeChat = state.activeChat === email;
  return {
    closeChat,
    activeChatType: closeChat ? 'chat' : state.activeChatType,
    reload: true,
  };
}
// ── ADR-005 W3 (партия 11): поток удаления контакта из UI ──────────────
// Подтверждение, снос ключа, применение состояния (закрытый чат),
// перечитывание списка контактов и сообщение об ошибке — логика диалога
// уехала из App.vue; UI-эффекты приходят deps'ами.
//
// ПОДТВЕРЖДЕНИЕ — ДО удаления. Если спросить после, то отказ диалога уже
// удалил контакт.
export async function deleteContactFlow(email, deps) {
  const {
    confirmDelete, removePeerKey, removalState, applyRemovalState,
    loadContacts, onError,
  } = deps;
  if (!(await confirmDelete())) return false;
  try {
    // Четыре шага и их порядок — в deleteContactLocally (см. шапку модуля):
    // снести ключ, пометить старые handshake по uid, снять наше приглашение,
    // убрать stub. Отказ любого шага останавливает остальные.
    await deleteContactLocally(email);
    removePeerKey(email);
    applyRemovalState(removalState(email));
    await loadContacts();
    return true;
  } catch (e) {
    // Состояние НЕ применяется: ключ мог снестись, а запись остаться.
    onError(e);
    return false;
  }
}

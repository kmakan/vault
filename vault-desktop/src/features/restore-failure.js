// Восстановление сессии: разбор причины отказа (ADR-003 Этап 3, партия 16).
//
// Метод showRestoreFailure читал состояние модуля api и раскладывал его по полям
// формы входа. Сама раскладка — чистая функция, и в ней три решения, которые
// легко потерять при переносе.
//
// ПРИЧИНА ОТКАЗА приходит из ядра (`vault::login_failure`, коды `auth`,
// `disabled`, `throttled`, `network`). Всё остальное — НЕ ошибка, а «не знаю»,
// и оно должно давать общий текст. Если бы незнакомая причина дала
// пустую строку, человек увидел бы форму входа без объяснения, почему его
// выбросило.
//
// КЛЮЧ ЛОКАЛИ И ЗАПАСНОЙ ТЕКСТ ЛЕЖАТ В ОДНОЙ ЗАПИСИ, и это не вкус.
//
// Первая версия держала две таблицы: `RESTORE_ERROR_KEYS` (причина → ключ) и
// `RESTORE_ERROR_FALLBACKS` (ключ → текст). Ключи в них не совпадали: первая
// давала 'restore_failed_auth', вторая была keyed как 'auth'. Разыскивание по
// второй таблице на ключе локали давало undefined, и МОЛЧА подставлялся общий
// текст — то есть запасные формулировки для 'отказ пароля' и 'нет сети'
// не могли быть показаны никогда. Тест это поймал: при переводчике, который
// ничего не знает, обе причины давали общий текст вместо своего.
//
// Пока ключ и текст разнесены по разным структурам, развести их можно снова.
// Одна запись делает это структурно невозможным.
//
// Запасные тексты не выбрасываются: t() возвращает undefined на незнакомый
// ключ, и тогда форма показала бы ПУСТОЕ поле ошибки, то есть никакой ошибки.
// Хуже всего для пользователя именно это — он был бы выброшен из сессии без
// объяснения.
//
// ПОРТЫ ПРИВОДЯТСЯ К СТРОКЕ. Поля imapPort/smtpPort привязаны к текстовым
// <input> через v-model, и без String() число порта попало бы в value как «993»
// вместо строки: v-model отдавал бы дальше число, и сравнение с сохранённой
// конфигурацией молча расходилось бы. Порт 0 при этом считается отсутствующим
// (нулевым портом не бывает), и поле остаётся пустым — так же, как при
// отсутствии.
//
// НАСТРОЙКИ ПОКАЗЫВАЮТСЯ ТОЛЬКО ЕСЛИ ИХ ЕСТЬ ОТ ЧЕГО ПОКАЗЫВАТЬ. При пустых
// серверах подсвечивать секцию настроек незачем: человеку, у которого просто не
// сохранился IMAP-хост, показывают форму с двумя пустыми полями и просят
// что-то исправить, хотя исправлять нечего.

import { detectProviderByServer } from '../mailProviders.js';

// Причина отказа → { ключ локали, запасной текст }. Ключ и текст неразлучны.
export const RESTORE_ERRORS = {
  auth: {
    key: 'restore_failed_auth',
    fallback: 'Пара email/пароль не сработала: пароль был изменён или отозван. Введите пароль заново.',
  },
  network: {
    key: 'restore_failed_network',
    fallback: 'Не удалось подключиться к почте: сервер недоступен или настройки IMAP/SMTP изменились. Проверьте интернет или откройте «Настройки сервера».',
  },
  // Два вердикта «не приговор паролю»: сервер не пустил по IMAP либо попросил
  // подождать. Главное для человека — сохранённый пароль НЕ удалён, то есть
  // вход вернётся сам, когда доступ включат или попытки улягутся.
  disabled: {
    key: 'restore_failed_imap_disabled',
    fallback: 'Почтовый сервер не пускает по IMAP: у провайдера мог быть выключен доступ «Почтовых программ». Сохранённый пароль мы не удаляли — включите доступ и попробуйте войти позже.',
  },
  throttled: {
    key: 'restore_failed_throttled',
    fallback: 'Слишком много попыток входа подряд — сервер просит подождать. Сохранённый пароль не удалён: подождите несколько минут и войдите снова.',
  },
  generic: {
    key: 'restore_failed_generic',
    fallback: 'Автоматический вход не удался. Войдите заново.',
  },
};

export function restoreErrorMessage(reason, t) {
  const e = RESTORE_ERRORS[reason] || RESTORE_ERRORS.generic;
  return t(e.key) || e.fallback;
}

// Порт → строка. 0 и отсутствие дают пустую строку.
function portToField(v) {
  return v ? String(v) : '';
}

export function restoreConfigFields(config) {
  const c = config || {};
  return {
    imapServer: c.imap_server || '',
    imapPort: portToField(c.imap_port),
    smtpServer: c.smtp_server || '',
    smtpPort: portToField(c.smtp_port),
  };
}

// Всё состояние формы входа после неудачного восстановления.
export function buildRestoreFailureState(reason, config, t) {
  const fields = restoreConfigFields(config);
  return Object.assign({}, fields, {
    loginError: restoreErrorMessage(reason, t),
    showServerSettings: !!(fields.imapServer || fields.smtpServer),
    // Селект провайдера восстанавливаем по сохранённому IMAP-хосту, чтобы
    // человек видел, какой провайдер был выбран, и не искал его в списке.
    mailProvider: detectProviderByServer(fields.imapServer),
  });
}
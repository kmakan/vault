// Два независимых правила, которые жили в компоненте:
//
//  * ПРАВИЛО МНОЖЕСТВЕННОГО ЧИСЛА. Русский язык требует трёх форм
//    («1 участник», «2 участника», «5 участников»), и переходы между ними
//    не совпадают с английскими («1 member», «2 members»). Ошибка здесь
//    заметна глазом, но не падает: текст просто выглядит неграмотно.
//
//  * ВСТАВКА ЭМОДЗИ. Пишет символ в поле ввода и закрывает выборщик;
//    фокус в поле не должен теряться.
//
// deps (ADR-001 R3): всё, что нужно снаружи, — явными параметрами.

// Правило множественного числа для подписи участников.
// locale — код локали ('ru', 'en', …); n — число.
export function membersLabel(locale, n) {
  const lang = String(locale || 'en').slice(0, 2);
  if (lang === 'ru') {
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return 'участник';
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'участника';
    return 'участников';
  }
  return n === 1 ? 'member' : 'members';
}

// Вставить эмодзи в поле ввода и закрыть выбор.
export function insertEmoji(deps, emoji) {
  deps.setNewMessage(deps.newMessage() + emoji);
  deps.setShowEmojiPicker(false);
}

// Capability-токены канала — примитив над Rust. Живёт ОТДЕЛЬНО от
// features/channels.js намеренно, и это не вопрос вкуса.
//
// ЗАЧЕМ ВЫНЕСЕНО. Транспорт (relay-client.js) обязан знать адрес очереди
// канала, а считает его фича features/channels.js. Из-за этого транспорт
// импортировал фичу, а фича импортировала транспорт (для публикации) —
// получался цикл. Цикл в ES-модулях не падает, но ставит порядок инициализации
// в контракт: правка одной стороны ломает другую не там, где правили. Адреса
// каналов к фиче отношения не имеют — это криптографический примитив, как и
// содержимое ./crypto.js.
//
// СЛОИ. Примитивы (этот файл, crypto.js) → транспорт (relay-client.js,
// api.js) → фичи (features/*) → компоненты. Стрелка только вниз. Обратная
// стрелка = цикл = правка одного модуля задевает другой.
//
// ADR-001: HMAC-SHA256 и раскладка 45-байтового capability-токена уехали в
// Rust (src-tauri/src/channels.rs::channel_tokens). Раньше считались здесь
// через crypto.subtle — это была единственная реальная крипто-математика в
// JS, и по итогу раскладка была описана в двух местах: здесь и в релее
// (vault-relay/src/tokens.rs). Правка одной стороны ломала другую тихо и
// всплывала как «каналы перестали работать». Теперь источник истины один, а
// совпадение с релеем запинено общими тест-векторами в Rust.
//
// Токены ДЕТЕРМИНИРОВАНЫ по ключу канала и никогда не меняются: смена токена
// = смена адреса очереди, и подписчики со старым адресом молча теряют канал
// (инцидент 12.10). Поэтому кэш здесь не «оптимизация», а защита от лишних
// IPC-вызовов.
import { invoke } from '@tauri-apps/api/core';

const _chanTokCache = new Map(); // keyHex → {read, write}

export async function channelTokens(keyHex) {
  const key = (keyHex || '').trim();
  const hit = _chanTokCache.get(key);
  if (hit) return hit;
  const [read, write] = await invoke('channels_tokens', { keyHex: key });
  const out = Object.freeze({ read, write });
  _chanTokCache.set(key, out);
  return out;
}
// Модуль-владелец состояния переписки (ADR-004, Этап A1).
//
// ЗАЧЕМ ЭТОТ ФАЙЛ, КОГДА ПЕРЕПИСКА УЖЕ ЕСТЬ В App.vue.
//
// Восемь модулей пишут в ctx.messages — attachments, calls, groups, history,
// messages, poll, reactions, send — и между ними нет ничего, кроме имени поля.
// Правка одного может испортить переписку и сломать остальные семь, а они об
// этом не узнают, потому что о нём ничего не знают.
//
// ctx здесь лишь ТРАНСПОРТ для этого канала. Пока канал есть, переименовать его
// в «зависимость» не поможет: канал останется, изменится имя.
//
// ЗДЕСЬ НЕ ПЕРЕХОДИТСЯ НИ ОДНА ЗАПИСЬ. Это подэтап A1: владелец и его API
// появляются раньше первого перенесённого модуля, чтобы каждая последующая
// замена была механической. Перенос всех восьми за один заход означал бы
// правку восьми модулей разом — ровно то, чем ADR-004 запрещает пользоваться.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ ИМПОРТА VUE.
//
// Первая версия брала `reactive` из vue внутри себя, и смоук не запускался:
// копия модуля лежит в /tmp, а node_modules оттуда не достижим.
//
// Это отказ инструмента, но он указал на более правильную форму. Владелец
// состояния НЕ ДОЛЖЕН знать о фреймворке:
//   · тогда он тестируется где угодно и чем угодно — Node, vitest, будущий
//     отдельный процесс;
//   · тогда решение о реактивности принимает композиционный корень, а не
//     доменный модуль: `const chat = reactive(createChatStore())`.
//
// Реактивность при этом сохраняется, и не случайно: методы мутируют state
// ЧЕРЕЗ объект-параметр, поэтому проходят через прокси, и подписки срабатывают.
// Если бы методы держали ссылку на сырой объект в замыкании, мутации шли бы
// мимо прокси и интерфейс перестал бы обновляться — тихо.

// Создаётся один раз на приложение (в композиционном корне).
export function createChatStore() {
  const state = {
    // Переписка открытого чата. Порядок важен: сообщения сортируются по времени
    // на месте (calls.js), и сортировка меняет этот массив.
    messages: [],
  };

  // ── Чтение ─────────────────────────────────────────────────────────────
  const list = () => state.messages;

  // ── Запись ─────────────────────────────────────────────────────────────
  //
  // ПОЧЕМУ API такой узкий. Разбор всех операций записи в ctx.messages дал
  // почти исключительно ЗАМЕНУ МАССИВА целиком, а не мутацию элементов:
  //   ctx.messages = []            очистка
  //   ctx.messages = [...list]     перечитывание списка
  //   ctx.messages = merged        слияние с локальной историей
  //   ctx.messages.push(msg)       оптимистичная запись
  //   ctx.messages.sort(...)       сортировка на месте (единственный случай)
  //
  // Значит API — это замена, добавление, сортировка и очистка. Методов правки
  // отдельного сообщения здесь нет намеренно: они понадобятся, когда
  // addReaction начнёт ходить через владельца, и тогда их вид будет определяться
  // этим местом, а не догадкой.

  // Полная замена содержимого. Принимает готовый массив — копия не делается:
  // копия означала бы двойное владение, то есть ровно ту неоднозначность,
  // которую этот модуль устраняет. Вызывающий сам решает, копировать ли ему.
  const set = (next) => { state.messages = next; return state.messages; };

  const clear = () => set([]);

  const byId = (id) => state.messages.find((m) => m && m.id === id) || null;

  // Добавление ОДНОГО сообщения.
  //
  // ДУБЛЬ ОТБРАСЫВАЕТСЯ, И ЭТО НЕ КОСМОЕТИКА. Из шести мест `ctx.messages.push`
  // в коде защиту от дубля проверяет ОДНО — calls.js, и проверяет руками:
  //
  //   const exists = (ctx.messages || []).some(m => m && m.id === msg.id);
  //   if (!exists) ctx.messages.push(msg);
  //
  // Остальные пять добавляют без проверки. Правило «одно сообщение — один id»
  // держится на памяти автора в шести местах, причём в пяти оно не написано.
  // Стоит ли оно во владельце — единственное место, где его нельзя забыть:
  // забыть проверку в шести вызывающих кодах можно, забыть её в одном
  // владельце — нет.
  //
  // ПОЧЕМУ ВОЗВРАЩАЕТСЯ БУЛЕВО, А НЕ САМО СООБЩЕНИЕ. Отбрасывание дубля —
  // молчаливое действие: вызывающий должен узнать, что его сообщение не
  // появилось. Если вернуть само сообщение, вызывающий посчитает успехом то,
  // чего не случилось, — и ошибка уйдёт дальше по коду незамеченной. Именно так
  // и выглядит поломка, которую потом ищут неделю.
  const append = (msg) => {
    if (msg && msg.id != null && byId(msg.id)) return false;
    state.messages.push(msg);
    return true;
  };

  // Сортировка НА МЕСТЕ. Это единственное место, где владелец разрешает
  // мутировать порядок: calls.js сортирует переписку по времени после
  // изменения. Порядок массива — часть состояния, и прятать его в сортировщике
  // означало бы завести ещё одно место, где правят то же самое.
  const sortBy = (cmp) => { state.messages.sort(cmp); return state.messages; };

  // Удаление по идентификатору. Сообщение ищется по id, а не по индексу:
  // индекс протухает между поиском и удалением, и это источник тихой порчи.
  const removeById = (id) => {
    const i = state.messages.findIndex((m) => m && m.id === id);
    if (i < 0) return false;
    state.messages.splice(i, 1);
    return true;
  };

  return { state, list, set, clear, append, sortBy, removeById, byId };
}
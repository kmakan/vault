// Модуль-владелец состояния переписки (ADR-004, Этап A1).
//
// ЗАЧЕМ ЭТОТ ФАЙЛ, КОГДА ПЕРЕПИСКА УЖЕ ЕСТЬ В App.vue.
//
// Один модуль пишет в ctx.messages — messages (компонент-App.vue). Правка
// одного может испортить переписку, но остальных не заденуть — потому что
// остальных уже нет. Семь модулей переведены на владельца: poll (A2),
// history (A3), reactions (A4), send (A5), attachments (A6), groups (A7),
// calls (A8). Остался messages.js — компонент-источник, разгружаемый
// (draining), а не конвертируемый: когда у него не останется writes —
// свойство messages в App.vue можно удалить.
//
// ctx здесь лишь ТРАНСПОРТ для этого канала. Пока канал есть, переименовать его
// в «зависимость» не поможет: канал останется, изменится имя.
//
// Владелец и его API появились раньше первого перенесённого модуля (A1), чтобы
// каждая последующая замена была механической. Перенос оставшихся пяти — по
// одному модулю за заход: правка всех разом была бы ровно тем, чем ADR-004
// запрещает пользоваться.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ ИМПОРТА VUE.
//
// Первая версия брала `reactive` из vue внутри себя, и смоук не запускался:
// копия модуля лежит в /tmp, а node_modules оттуда не достижим.
//
// Это отказ инструмента, но он указал на более правильную форму. Владелец
// состояния НЕ ДОЛЖЕН знать о фреймворке:
//   · тогда он тестируется где угодно и чем угодно — Node, vitest, будущий
//     отдельный процесс;
//   · тогда решение о реактивности принимает композиционный корень, а не
//     доменный модуль: `const chat = reactive(createChatStore())`.
//
// Реактивность при этом сохраняется, и не случайно: методы мутируют state
// ЧЕРЕЗ объект-параметр (this.state), поэтому проходят через прокси, и
// подписки срабатывают. Если бы методы держали ссылку на сырой объект в
// замыкании, мутации шли бы мимо прокси и интерфейс перестал бы обновляться —
// тихо.

// Создаётся один раз на приложение (в композиционном корне).
export function createChatStore() {
  return {
    // Переписка открытого чата. Порядок важен: сообщения сортируются по времени
    // на месте (calls.js), и сортировка меняет этот массив.
    // unreadCounts — счётчики непрочитанных по чатам (chat-store владелец,
    // ADR-004 A11; писателей 2: calls.js + incoming.js, до перехода на owner).
    state: {
      messages: [],
      unreadCounts: {},
      // Текущий черновик composer (ADR-004 A14). Писателей 2: drafts.js
      // (restore draft) + send.js (clear после отправки). Остальные — READ.
      newMessage: '',
    },

    // ── newMessage / draft (ADR-004 A14) ────────────────────────────────
    // Текст сообщения, которое пользователь набирает в composer. Владелец
    // гарантирует: drafts.js и send.js пишут через setDraft/clearDraft, а не
    // напрямую. READ в template/send.js/drafts.js — через computed proxy.
    setDraft(text) {
      this.state.newMessage = text == null ? '' : String(text);
      return this.state.newMessage;
    },
    getDraft() {
      return this.state.newMessage;
    },
    clearDraft() {
      this.state.newMessage = '';
      return this.state.newMessage;
    },

    // ── unreadCounts (ADR-004 A11) ────────────────────────────────────────────
    // Инкремент счётчика непрочитанных для чата. Владелец гарантирует
    // атомарность read-modify-write: раньше два модуля (calls/incoming)
    // делали `ctx.unreadCounts[k] = (ctx.unreadCounts[k]||0)+1` независимо —
    // race мог дать 1 вместо 2 при параллельном missed-входящем и email.
    incUnread(chatKey) {
      const b = this.state.unreadCounts[chatKey] || 0;
      this.state.unreadCounts[chatKey] = b + 1;
      return this.state.unreadCounts[chatKey];
    },
    // Сброс счётчика (чат стал видимым / пометка прочитанного).
    clearUnread(chatKey) {
      delete this.state.unreadCounts[chatKey];
      return this.state.unreadCounts;
    },
    // Полный сброс (logout/reset), сохраняет реактивность proxy.
    clearAllUnread() {
      this.state.unreadCounts = {};
      return this.state.unreadCounts;
    },
    // Текущий счётчик для чата.
    unreadOf(chatKey) {
      return this.state.unreadCounts[chatKey] || 0;
    },
    // Полная замена (bulk-load из kv после рестарта). Вызывающий решает,
    // копировать ли массив — см. set(). Используется App.vue loadUnreadCounts.
    setUnread(map) {
      this.state.unreadCounts = map || {};
      return this.state.unreadCounts;
    },

    // ── Чтение ───────────────────────────────────────────────────────────
    list() {
      return this.state.messages;
    },

    // ── Запись ───────────────────────────────────────────────────────────
    //
    // ПОЧЕМУ API такой узкий. Разбор всех операций записи в ctx.messages дал
    // почти исключительно ЗАМЕНУ МАССИВА целиком, а не мутацию элементов:
    //   ctx.messages = []            очистка
    //   ctx.messages = [...list]     перечитывание списка
    //   ctx.messages = merged        слияние с локальной историей
    //   ctx.messages.push(msg)       оптимистичная запись
    //   ctx.messages.sort(...)       сортировка на месте (единственный случай)
    //
    // Значит API — это замена, добавление, сортировка, очистка и мутация
    // элемента (patch). Методов правки отдельного сообщения здесь не было
    // намеренно до A4: их вид должен определяться этим местом, а не догадкой, —
    // и patch появился, когда addReaction перешёл на владельца.

    // Полная замена содержимого. Принимает готовый массив — копия не делается:
    // копия означала бы двойное владение, то есть ровно ту неоднозначность,
    // которую этот модуль устраняет. Вызывающий сам решает, копировать ли ему.
    set(next) {
      this.state.messages = next;
      return this.state.messages;
    },

    clear() {
      return this.set([]);
    },

    byId(id) {
      return this.state.messages.find((m) => m && m.id === id) || null;
    },

    // Добавление ОДНОГО сообщения.
    //
    // ДУБЛЬ ОТБРАСЫВАЕТСЯ, И ЭТО НЕ КОСМЕТИКА. Из шести мест `ctx.messages.push`
    // в коде защиту от дубля проверяет ОДНО — calls.js, и проверяет руками:
    //
    //   const exists = (ctx.messages || []).some(m => m && m.id === msg.id);
    //   if (!exists) ctx.messages.push(msg);
    //
    // Остальные пять добавляют без проверки. Правило «одно сообщение — один id»
    // держится на памяти автора в шести местах, причём в пяти оно не написано.
    // Стоит ли оно во владельце — единственное место, где его нельзя забыть:
    // забыть проверку в шести вызывающих кодах можно, забыть её в одном
    // владельце — нет.
    //
    // ПОЧЕМУ ВОЗВРАЩАЕТСЯ БУЛЕВО, А НЕ САМО СООБЩЕНИЕ. Отбрасывание дубля —
    // молчаливое действие: вызывающий должен узнать, что его сообщение не
    // появилось. Если вернуть само сообщение, вызывающий посчитает успехом то,
    // чего не случилось, — и ошибка уйдёт дальше по коду незамеченной. Именно так
    // и выглядит поломка, которую потом ищут неделю.
    append(msg) {
      if (msg && msg.id != null && this.byId(msg.id)) return false;
      this.state.messages.push(msg);
      return true;
    },

    // Мутация элемента по id. Единственный способ изменить отдельное сообщение
    // через владельца: вызывающий передаёт функцию, которая получает ссылку
    // на элемент и мутирует его.
    //
    // ЗАЧЕМ НЕ ВОЗВРАЩАТЬ ЭЛЕМЕНТ. Если вернуть элемент, вызывающий может
    // сохранить ссылку и изменить её позже — мимо владельца. Это уже не
    // запись через владельца, а запись через украденную ссылку.
    //
    // ЗАЧЕМ ФУНКЦИЯ, А НЕ ОБЪЕКТ ИЗМЕНЕНИЙ. Объект изменений пришлось бы
    // интерпретировать (merge? replace? глубоко?), и это ещё один формат,
    // который нужно поддерживать. Функция передаёт всю логику мутации в
    // вызывающего, а владелец лишь гарантирует, что она применится к
    // существующему элементу через прокси.
    patch(id, fn) {
      const msg = this.byId(id);
      if (!msg) return false;
      fn(msg);
      return true;
    },

    // Сортировка НА МЕСТЕ. Это единственное место, где владелец разрешает
    // мутировать порядок: calls.js сортирует переписку по времени после
    // изменения. Порядок массива — часть состояния, и прятать его в сортировщике
    // означало бы завести ещё одно место, где правят то же самое.
    sortBy(cmp) {
      this.state.messages.sort(cmp);
      return this.state.messages;
    },

    // Удаление по идентификатору. Сообщение ищется по id, а не по индексу:
    // индекс протухает между поиском и удалением, и это источник тихой порчи.
    removeById(id) {
      const i = this.state.messages.findIndex((m) => m && m.id === id);
      if (i < 0) return false;
      this.state.messages.splice(i, 1);
      return true;
    },
  };
}

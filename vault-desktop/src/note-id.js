// Идентификатор заметки для себя — одна формула на проект.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Формула id заметки была в трёх местах
// (features/chat.js, features/attachments.js ×2) и копии разошлись: в chat.js
// время инъецировалось (чистота для смоука), в attachments.js — бралось из
// Date.now() прямо на месте. Правило «как называется заметка» должно быть
// одно: иначе при слиянии/поиске заметки по id одна ветка не найдёт другую.
//
// Это ЛОКАЛЬНЫЙ id (заметка лежит в localStorage, на провод не идёт) —
// поэтому правило живёт в JS, а не в Rust: формат провода его не касается.
//
// now инъецируется — ради чистоты смоуков (как и раньше в chat.js).
export function noteId(now = Date.now()) {
  return 'note-' + now.toString(36) + Math.random().toString(36).substr(2, 5);
}

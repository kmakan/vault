// Набор мутаций: rust-bridge-security — первое измерение МОСТА.
//
// ЗАЧЕМ. Движок меряет только тот крейт, что указан в `crate`, и за всю
// программу ни одного набора с `crate: 'vault-desktop/src-tauri'` не было:
// 170 тестов моста не проверялись подложенной поломкой никогда. Пятнадцатая
// волна (24.10) показала цену — компаратор порядка групп жил в команде моста,
// а тесты сортировали своей копией, и удаление реальной строки было зелёным.
//
// ВЫБРАНО ДЛЯ ПЕРВОГО НАБОРА. `sanitize_filename`: имя вложения присылает
// отправитель, это НЕ доверенный ввод, и `dir.join(filename)` с `../` увёл бы
// запись из каталога загрузок. Правило осталось в мосту осознанно (это форма
// имени для файловой системы, а не протокол), но от этого оно не перестаёт
// быть решением — значит оно обязано быть измерено так же, как правила ядра.
//
// `crate` — каталог, `pkg` — имя пакета: у моста они разные, и cargo путь
// вместо имени не принимает. Первая попытка без `pkg` дала «тесты не проходят
// на чистом дереве» — движок путал собранный лифт с упавшим тестом, теперь
// базовый прогон печатает причину.
export default {
  id: 'rust-bridge-security',
  crate: 'vault-desktop/src-tauri',
  pkg: 'vault-desktop',
  file: 'vault-desktop/src-tauri/src/vault_bridge.rs',
  smoke: 'cargo test -p vault-desktop --lib',
  kind: 'lib',
  // Мост тяжёлый: на холодном кеше (CI пересобирает tauri-крейт) каждая из
  // пяти сборок проглатывает дефолтные 600 секунд движка, и прогон обрывался
  // посреди набора. Потолок поднят до 20 минут на прогон.
  timeoutMs: 1_200_000,
  mutations: [
    { name: 'имя берётся до первого слэша (путь не отрезается, а обрубается с головы)',
      pattern: "    let base = name.rsplit(['/', '\\\\']).next().unwrap_or(\"\");",
      replacement: "    let base = name.split(['/', '\\\\']).next().unwrap_or(\"\");" },
    { name: 'управляющие символы из имени не вырезаются (перевод строки в имени файла)',
      pattern: '    let cleaned: String = base.chars().filter(|c| !c.is_control()).collect();',
      replacement: '    let cleaned: String = base.chars().collect();' },
    { name: 'ведущие точки остаются (двойная точка становится именем)',
      pattern: '    let trimmed = cleaned.trim().trim_start_matches(\'.\').trim();',
      replacement: '    let trimmed = cleaned.trim();' },
    { name: 'пустое имя не заменяется на заглушку (запись в несуществующее имя)',
      pattern: '    if trimmed.is_empty() {\n        "file".to_string()',
      replacement: '    if false {\n        "file".to_string()' },
  ],
};

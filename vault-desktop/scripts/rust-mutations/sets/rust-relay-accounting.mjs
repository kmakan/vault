//   • сроки: чек — 9-е, налог — 28-е следующего месяца;
//   • границы дохода: статус (pending/canceled не деньги), валюта, сумма, дата;
//   • просрочки чека и налога, отметку «налог уплачен»;
//   • разбор «149.00» и формат «149,00 ₽»;
//   • экранирование HTML и CSRF в формах страницы;
//   • страж реестра (мусорные ключи) и права файла реестра (0600).

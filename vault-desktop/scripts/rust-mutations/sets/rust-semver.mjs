// Набор мутаций: rust-semver — численное сравнение версий релиза.
//
// ЗАЧЕМ. «Новее ли удалённая версия» жило внутри `check_app_update` во мосту,
// то есть в функции с TLS, HTTP и разбором `latest.json`: тест требовал сети,
// `rust-mutation-gate` мост не мерит — значит поломка обновления (клиент
// вечно молчит или вечно предлагает установку) замечалась только вручную.
// Перенесённая в ядро, эта арифметика наконец под проверкой.
//
// Каталог ошибок, которые ловят наборы ниже: лексикографическое сравнение
// («0.1.9» больше «0.1.255» — обновление перестаёт приходить ровно на переходе
// минора за девятку), решение по первому компоненту без сверки, игнор хвоста
// короткой версии, `v`-префикс как часть числа.
export default {
  id: 'rust-semver',
  file: 'vault-client/src/vault/semver.rs',
  smoke: 'cargo test -p vault-client --lib',
  mutations: [
    { name: 'компоненты читаются до первой точки (хвост версии игнорируется: 1.2.1 == 1.2)',
      pattern: "        .split(|c: char| !c.is_ascii_digit())",
      replacement: "        .split('.')" },
    { name: 'пустые токены не отбрасываются (v-префикс превращается в нулевой компонент сдвига)',
      pattern: '        .filter(|p| !p.is_empty())',
      replacement: '        .filter(|_| true)' },
    { name: 'короткая версия дополняется максимумом, а не нулями (1.2 оказывается новее 1.2.0)',
      pattern: '            av.get(i).copied().unwrap_or(0),\n            bv.get(i).copied().unwrap_or(0)',
      replacement: '            av.get(i).copied().unwrap_or(u64::MAX),\n            bv.get(i).copied().unwrap_or(0)' },
    { name: 'сравнивается только пересечение длин (1.2.0.1 перестаёт быть новее 1.2.0)',
      pattern: '    for i in 0..av.len().max(bv.len()) {',
      replacement: '    for i in 0..av.len().min(bv.len()) {' },
    { name: 'вердикт выносится на первом же компоненте, равном тоже (сравнение ломается на старте)',
      pattern: '        if x != y {',
      replacement: '        if true {' },
    { name: 'сравнение перевёрнуто (клиент считает новой ту версию, что старше)',
      pattern: '            return x > y;',
      replacement: '            return y > x;' },
    { name: 'равные версии считаются новым релизом (бесконечное предложение установки самой себя)',
      pattern: '        if x != y {\n            return x > y;\n        }',
      replacement: '        if x >= y {\n            return true;\n        }' },
  ],
};
